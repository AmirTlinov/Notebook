"""The verification registry owns check scope, preparation and evidence names.

Profiles are tags on checks. Full verification uses the same executors and
parsers; physical acceptance remains a separately observed user scenario.
"""
from dataclasses import dataclass


@dataclass(frozen=True)
class Check:
    id: str
    contract: str
    platform: str
    selectors: tuple[str, ...]
    profiles: tuple[str, ...] = ()
    prerequisites: tuple[str, ...] = ()
    parser: str = "xcresult"
    command: tuple[str, ...] = ()
    evidence: tuple[str, ...] = ()
    full: bool = False
    owner: str = ""
    success: str = "passed"


def native(check_id, contract, platform, selectors, profiles=(), full=False):
    prerequisites = ("project", "typesetter") + (("mcp-dependencies", "codex", "typescript") if platform == "mac" else ("physical-ipad", "unlocked-ipad"))
    return Check(check_id, contract, platform, tuple(selectors), tuple(profiles), prerequisites,
                 "xcresult", ("xcrun", "xcodebuild"),
                 tuple(platform + suffix for suffix in ("-inventory.json", ".xcresult", "-summary.json", "-tests.json", "-execution.json"))
                 + (("physical-ipad.json", "physical-ipad-lock-state.json", "physical-ipad-lock-state-inventory.json",
                     "physical-ipad-lock-state-execution.json") if platform == "ipad" else ()), full, owner=check_id.split("/", 1)[0])


def core(check_id, contract, selectors, profiles=(), full=False, prerequisites=()):
    return Check(check_id, contract, "core", tuple(selectors), tuple(profiles), tuple(prerequisites), "swift-events",
                 ("swift", "test"), ("core-inventory.jsonl", "core-*-events.jsonl", "core-execution.json"), full, owner=check_id.split("/", 1)[0])


def portable(check_id, contract, parser, command, profiles=(), prerequisites=(), full=True, success="passed"):
    return Check(check_id, contract, "commands", (), tuple(profiles), tuple(prerequisites), parser,
                 tuple(command), (check_id + "-inventory.json", check_id + "-execution.json"), full, owner=check_id, success=success)


