// The public JSON schemas are the only source of domain types. This renderer
// does not execute user code or embed a second TypeScript compiler.
export function sdkDeclarations(contract) {
  const output = ['// Generated by MCP/build-script-services.mjs. Do not edit.', 'declare namespace NotebookSDK {',
    'export type JSONValue = null | boolean | number | string | JSONValue[] | { [key: string]: JSONValue };'];
  const identifier = value => value.replace(/[^A-Za-z0-9_]/g, '_');
  function declare(name, schema) {
    const defs = schema.$defs ?? {};
    function type(s) {
      if(s === false) return 'never';
      if(s === true || !s || Object.keys(s).length === 0) return 'unknown';
      if(s.$ref) {
        if(s.$ref === '#') return name;
        if(!s.$ref.startsWith('#/$defs/')) throw new Error('Non-local SDK type reference: '+s.$ref);
        return name+'_'+identifier(s.$ref.slice(8));
      }
      if(Object.hasOwn(s,'const')) return JSON.stringify(s.const);
      if(s.enum) return s.enum.map(x=>JSON.stringify(x)).join(' | ');
      if(s.anyOf || s.oneOf) return '('+(s.anyOf??s.oneOf).map(type).join(' | ')+')';
      if(s.allOf) return '('+s.allOf.map(type).join(' & ')+')';
      if(Array.isArray(s.type)) return '('+s.type.map(t=>type({...s,type:t})).join(' | ')+')';
      switch(s.type) {
        case 'null':return 'null';
        case 'boolean':return 'boolean';
        case 'integer':case 'number':return 'number';
        case 'string':return 'string';
        case 'array':return s.prefixItems ? '['+s.prefixItems.map(type).join(', ')+']' : '('+type(s.items)+')[]';
        case 'object': {
          const fields=Object.entries(s.properties??{}).map(([key,value])=>JSON.stringify(key)+(s.required?.includes(key)?'':'?')+': '+type(value)+';');
          const open = s.additionalProperties === true || (s.additionalProperties && Object.keys(s.additionalProperties).length === 0);
          if(s.additionalProperties !== false && (!open || !Object.keys(s.properties??{}).length)) fields.push('[key: string]: '+type(s.additionalProperties??true)+';');
          return '{ '+fields.join(' ')+' }';
        }
        default:return 'unknown';
      }
    }
    for(const [key,value] of Object.entries(defs)) output.push('type '+name+'_'+identifier(key)+' = '+type(value)+';');
    output.push('export type '+name+' = '+type(schema)+';');
  }
  declare('ReadBasis',contract.common.basis); declare('Coverage',contract.common.coverage); declare('ActionResult',contract.common.actionResult);
  for(const [name,method] of Object.entries(contract.methods)) {
    declare(name+'Input',method.input); if(!['read','readMany'].includes(name)) declare(name+'Output',method.output);
  }
  for(const [kind,schema] of Object.entries(contract.readData)) declare('Read_'+kind,schema);
  output.push('export interface ReadData { '+Object.keys(contract.readData).map(k=>k+': Read_'+k+';').join(' ')+' }',
    'export type ReadQuery = readInput;',
    'export interface Snapshot<T> { data: T; basis: ReadBasis; coverage: Coverage; cursor: string; }',
    'export interface BatchSnapshot<T> extends Snapshot<T> { coverages: Coverage[]; }',
    'export interface Client {',
    'read<const Q extends ReadQuery>(query: Q): Promise<Snapshot<ReadData[Q["kind"]]>>;',
    'readMany<const Q extends readonly ReadQuery[]>(request: {queries: Q; expectedCursor?: string}): Promise<BatchSnapshot<{[K in keyof Q]: ReadData[Q[K]["kind"]]}>>;',
    'page(args: pageInput & {elementID: string}): Promise<Snapshot<Read_pageElement>>;',
    'page(args?: pageInput & {elementID?: never}): Promise<Snapshot<Read_page>>;',
    'document(args: documentInput & {blockID: string}): Promise<Snapshot<Read_documentBlock>>;',
    'document(args?: documentInput & {blockID?: never}): Promise<Snapshot<Read_document>>;');
  for(const name of Object.keys(contract.methods)) {
    if(['read','readMany','page','document','emit','emitImage'].includes(name)) continue;
    let args='args: '+name+'Input';
    if(name === 'help') args='topic?: string';
    if(name === 'id') args='key: string';
    if(name === 'transaction') args='key: string, action: transactionInput["action"]';
    if(['undo','point','present','cancelPresentation','export'].includes(name)) args='key: string, args: Omit<'+name+'Input, "key">';
    if(['observe','board','context','presentation'].includes(name)) args='args?: '+name+'Input';
    output.push(name+'('+args+'): Promise<'+name+'Output>;');
  }
  output.push('}', '}', 'declare const nb: NotebookSDK.Client;', 'declare const args: NotebookSDK.JSONValue;',
    'declare function emit(value: unknown): Promise<NotebookSDK.emitOutput>;',
    'declare function emitImage(artifact: NotebookSDK.emitImageInput["artifact"]): Promise<NotebookSDK.emitImageOutput>;', '');
  return output.join('\n');
}
